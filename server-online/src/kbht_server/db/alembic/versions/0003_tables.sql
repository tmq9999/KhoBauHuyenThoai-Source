-- Frozen additive inventory/reward DDL.
CREATE TABLE item_definitions (
	content_version_id UUID NOT NULL,
	kind_id BIGINT NOT NULL,
	stack_limit BIGINT NOT NULL,
	PRIMARY KEY (content_version_id, kind_id),
	CONSTRAINT ck_item_definition_id CHECK (kind_id BETWEEN 1 AND 9007199254740991),
	CONSTRAINT ck_item_stack_limit CHECK (stack_limit BETWEEN 1 AND 9007199254740991),
	FOREIGN KEY(content_version_id) REFERENCES content_versions (id)
);

CREATE TABLE inventory_items (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10001 MAXVALUE 9007199254740991),
	player_id BIGINT NOT NULL,
	content_version_id UUID NOT NULL,
	kind_id BIGINT NOT NULL,
	stack_key VARCHAR(64) NOT NULL,
	quantity BIGINT NOT NULL,
	version BIGINT NOT NULL,
	created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
	updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
	PRIMARY KEY (id),
	FOREIGN KEY(content_version_id, kind_id) REFERENCES item_definitions (content_version_id, kind_id),
	CONSTRAINT uq_inventory_stack UNIQUE (player_id, kind_id, stack_key),
	CONSTRAINT uq_inventory_owner_kind UNIQUE (id, player_id, kind_id),
	CONSTRAINT ck_inventory_quantity CHECK (quantity BETWEEN 0 AND 9007199254740991),
	CONSTRAINT ck_inventory_version CHECK (version BETWEEN 1 AND 9007199254740991),
	FOREIGN KEY(player_id) REFERENCES players (id)
);

CREATE TABLE reward_grants (
	id UUID NOT NULL,
	player_id BIGINT NOT NULL,
	command_id UUID NOT NULL,
	content_version_id UUID NOT NULL,
	source_type VARCHAR(64) NOT NULL,
	source_id UUID NOT NULL,
	payload_hash VARCHAR(64) NOT NULL,
	result_json JSONB NOT NULL,
	created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
	PRIMARY KEY (id),
	CONSTRAINT uq_reward_source UNIQUE (player_id, source_type, source_id),
	CONSTRAINT uq_reward_content UNIQUE (id, content_version_id),
	CONSTRAINT uq_reward_owner UNIQUE (id, player_id),
	FOREIGN KEY(player_id, command_id) REFERENCES command_receipts (player_id, command_id) DEFERRABLE INITIALLY DEFERRED,
	FOREIGN KEY(player_id) REFERENCES players (id),
	FOREIGN KEY(content_version_id) REFERENCES content_versions (id)
);

CREATE TABLE inventory_ledger (
	id UUID NOT NULL,
	inventory_id BIGINT NOT NULL,
	player_id BIGINT NOT NULL,
	kind_id BIGINT NOT NULL,
	command_id UUID NOT NULL,
	content_version_id UUID NOT NULL,
	delta BIGINT NOT NULL,
	quantity_after BIGINT NOT NULL,
	inventory_version BIGINT NOT NULL,
	reason VARCHAR(160) NOT NULL,
	source_type VARCHAR(64) NOT NULL,
	source_id UUID NOT NULL,
	reward_grant_id UUID,
	created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
	PRIMARY KEY (id),
	FOREIGN KEY(inventory_id, player_id, kind_id) REFERENCES inventory_items (id, player_id, kind_id),
	FOREIGN KEY(content_version_id, kind_id) REFERENCES item_definitions (content_version_id, kind_id),
	FOREIGN KEY(player_id, command_id) REFERENCES command_receipts (player_id, command_id) DEFERRABLE INITIALLY DEFERRED,
	FOREIGN KEY(reward_grant_id, player_id) REFERENCES reward_grants (id, player_id) DEFERRABLE INITIALLY DEFERRED,
	CONSTRAINT uq_inventory_ledger_version UNIQUE (inventory_id, inventory_version),
	CONSTRAINT ck_inventory_delta CHECK (delta != 0 AND delta BETWEEN -9007199254740991 AND 9007199254740991),
	CONSTRAINT ck_inventory_after CHECK (quantity_after BETWEEN 0 AND 9007199254740991),
	CONSTRAINT ck_inventory_ledger_version CHECK (inventory_version BETWEEN 1 AND 9007199254740991)
);

CREATE TABLE reward_currencies (
	grant_id UUID NOT NULL,
	currency VARCHAR(32) NOT NULL,
	quantity BIGINT NOT NULL,
	PRIMARY KEY (grant_id, currency),
	CONSTRAINT ck_reward_currency_quantity CHECK (quantity BETWEEN 1 AND 9007199254740991),
	FOREIGN KEY(grant_id) REFERENCES reward_grants (id)
);

CREATE TABLE reward_items (
	grant_id UUID NOT NULL,
	kind_id BIGINT NOT NULL,
	content_version_id UUID NOT NULL,
	quantity BIGINT NOT NULL,
	PRIMARY KEY (grant_id, kind_id),
	FOREIGN KEY(grant_id, content_version_id) REFERENCES reward_grants (id, content_version_id),
	FOREIGN KEY(content_version_id, kind_id) REFERENCES item_definitions (content_version_id, kind_id),
	CONSTRAINT ck_reward_item_quantity CHECK (quantity BETWEEN 1 AND 9007199254740991)
);
